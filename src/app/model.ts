/**
 * Модель данных «Злотых» — дословно из `docs/02-Архитектура.md`.
 *
 * Форма записи решена по выгрузкам банков (Р-12); `Base`, `Migration`
 * и раскладка — договор семьи из ядра, здесь не переопределяются.
 *
 * Имена полей меняются только вместе с Архитектурой: она источник истины,
 * а не этот файл.
 */

import type { Base, Migration } from '../shared/core/model.ts'

// ─── Деньги (Р-04) ─────────────────────────────────────────────────────────

/**
 * Код валюты: 'RUB', 'USD', 'BTC', 'USDT'. Что он значит — в справочнике
 * `currencies`: перечисления в коде нет, новая валюта заводится записью (Р-12).
 */
export type CurrencyCode = string

/**
 * Сумма — целое число в минимальных единицах валюты: 123456 RUB = 1 234,56 ₽.
 * Всегда положительная: направление даёт `kind` операции (Р-12).
 */
export type Money = {
  amount: number
  currency: CurrencyCode
}

/** Курс на дату: 1 `from` = `rate` `to`. Дробный — законно: пересчёт не хранится. */
export type Rate = Base & {
  /** ГГГГ-ММ-ДД */
  date: string
  from: CurrencyCode
  to: CurrencyCode
  rate: number
  /** Публичный источник появится позже — своим именем (Р-04). */
  source: 'manual' | 'import' | string
}

// ─── Справочники ───────────────────────────────────────────────────────────

/** Валюта — запись, а не строка в коде: новая заводится из интерфейса (Р-12). */
export type Currency = Base & {
  code: CurrencyCode
  /** «Рубль», «Биткойн» */
  name: string
  /** Знаков в минимальной единице: 2 у рубля, 8 у BTC. Больше 8 не бывает (Р-04). */
  decimals: number
  /** Единица показа: mBTC — `{ name: 'mBTC', factor: 100000 }` */
  unit?: { name: string; factor: number }
  order: number
}

/**
 * Где лежат деньги. Одна валюта на счёт (Р-05).
 *
 * Счёт — банк целиком, а не карта и не вклад (Р-12): выписка банка ложится
 * на один счёт, движения внутри счёта не записываются.
 */
export type Account = Base & {
  /** Банк, наличные, брокерский счёт, кошелёк. */
  name: string
  currency: CurrencyCode
  /** Сбережения или вложения (Р-05). */
  kind: 'savings' | 'investment'
  /** Счёт истории: операции на него не загружаются никогда (Р-12). */
  ledgerOnly?: boolean
  /**
   * По какое число доведена выписка этого счёта, ГГГГ-ММ-ДД (Р-26).
   *
   * Не вывод из записей, а то, что выписка сказала о себе сама: конец
   * периода из раздела `checks`, записанный импортом, когда сверка сошлась.
   * Назад не откатывается. Нет поля — по этому счёту выписок не грузили
   * (наличные, ручной ввод), и срока он не задаёт.
   */
  loadedThrough?: string
  archived?: boolean
  order: number
}

/** За что потрачено или откуда пришло. Расходные и доходные — разные (Р-05). */
export type Category = Base & {
  name: string
  side: 'expense' | 'income'
  archived?: boolean
  order: number
}

/** Регулярная — шаблон, который сам ничего не пишет (Р-06). */
export type Recurring = Base & {
  /** «Связь», «Интернет», «Страховка» */
  name: string
  categoryId: string
  accountId?: string
  expected: Money
  /** 1 — раз в месяц, 12 — раз в год, N — раз в N месяцев. */
  every: { months: number }
  /** ГГГГ-ММ, с какого периода действует. */
  from: string
  /** ГГГГ-ММ, по какой; нет — действует. */
  to?: string
  order: number
}

/**
 * Настройки учёта, общие для всех устройств (Р-12).
 *
 * Запись одна; единственность держат код и тест — тип её не гарантирует.
 * Локальные настройки ядра для этого не годятся: они не уезжают на второе
 * устройство, там лежит токен.
 */
export type Profile = Base & {
  /** В ней считаются итоги. */
  baseCurrency: CurrencyCode
  /** Вторая валюта капитала. */
  showCurrency?: CurrencyCode
  /** 1 — календарный месяц; иное — свой отчётный период, экран позже. */
  periodStartDay?: number
  /** Цель нормы сбережений, доля: 0.2 — «откладывать 20%». */
  savingsGoal?: number
}

// ─── Записи учёта (Р-02, Р-12) ─────────────────────────────────────────────

/**
 * Операция — или итог периода там, где операций нет (Р-02).
 *
 * `transfer` — перевод между своими счетами: не расход и не доход. Движение
 * внутри одного счёта не записывается вовсе (Р-12).
 */
export type Entry = Base & {
  kind: 'expense' | 'income' | 'transfer'
  /** Откуда деньги ушли или куда пришли; у `transfer` — откуда. */
  accountId: string
  /** Всегда в валюте счёта, всегда положительная. */
  money: Money
  /** ГГГГ-ММ-ДД — операция. */
  date?: string
  /** ЧЧ:ММ, если банк его дал; входит в ключ `ext`. */
  time?: string
  /** Итог периода вместо даты. */
  period?: { from: string; to: string }
  /** У `transfer` — нет; у итога периода — необязательна (Р-12). */
  categoryId?: string
  /** У `transfer`; может быть неизвестен — «второй счёт не указан». */
  toAccountId?: string
  /** Особая: во всех расходах есть, в обычном месяце нет (Р-05). */
  special?: boolean
  /** От какой регулярной (Р-06). */
  recurringId?: string
  /** ГГГГ-ММ — «за какой период», только для блока «Регулярные» (Р-06). */
  for?: string
  /** Исходная строка выписки, как пришла (Р-12). */
  bankText?: string
  /** Внешний ключ импорта: записывается один раз и не меняется (Р-12). */
  ext?: string
  /** Комментарии таблицы — сюда. */
  note?: string
  /** Связь с тратой комнаты, долгом или возвратом: в поток идёт доля (Р-31). */
  refs?: string[]
}

/**
 * Сколько было на счёте на дату. Не `Snapshot`: так в ядре называется
 * файл-копия.
 *
 * На одну дату и счёт — либо снимок без части, либо снимки по частям (Р-12);
 * вместе они не складываются, итог счёта — сумма частей.
 */
export type Balance = Base & {
  accountId: string
  /** ГГГГ-ММ-ДД */
  date: string
  /** Часть счёта: «карта», «накопительный». Нет — весь счёт. */
  part?: string
  /** В валюте счёта, целое. */
  amount: number
  note?: string
}

// ─── Долги (Р-01, Р-05, Р-30, Р-31) ────────────────────────────────────────

/**
 * Человек — один справочник на комнаты и разовые долги (Р-01).
 *
 * «Я» — обычный человек с пометкой `self`, а не подразумеваемый владелец:
 * у каждой траты плательщик и доли — люди по `id`, и «мои долги» идут через
 * пометку. Запись с `self` одна; единственность держат код и тест.
 */
export type Person = Base & {
  name: string
  self?: true
  archived?: boolean
}

/**
 * Комната — компания, на которую ведётся общий счёт: «Лето».
 *
 * Долгоживущая: поводов в ней много, и каждый — своё событие (Р-30).
 * Самостоятельна (условие 1 Р-01): всё её — события, траты, переводы —
 * ссылается на её `id` и вынимается без записей учёта.
 */
export type Room = Base & {
  name: string
  /** Одна на комнату: суммы внутри — целые в ней (условие 6 Р-01). */
  currency: CurrencyCode
  personIds: string[]
  closed?: boolean
}

/**
 * Повод, на который скидывались: «Падел, 21 августа» (Р-30).
 *
 * Состав хранится, а не выводится из трат: «поровну» должно знать, на кого
 * делить — на всю комнату или на троих, кто пошёл. Для новой траты это
 * подсказка, чем заполнить доли, а не правило, по которому пересчитываются
 * старые: доли уже записаны в самой трате.
 */
export type RoomEvent = Base & {
  roomId: string
  name: string
  /** ГГГГ-ММ-ДД */
  date: string
  personIds: string[]
  closed?: boolean
}

/**
 * Трата события: кто заплатил, сколько, на кого делится (Р-30).
 *
 * Доли записаны поимённо в момент заведения — запись знает, что случилось,
 * а не что сейчас настроено (тот же урок, что и Р-26). Трат вне событий нет.
 */
export type RoomSpend = Base & {
  eventId: string
  /** ГГГГ-ММ-ДД. Своя: подставляется из события и дальше живёт сама. */
  date: string
  title: string
  payerId: string
  /** Целое в валюте комнаты. */
  amount: number
  /**
   * Доля суммой (`share`) или весом (`weight`), не тем и другим сразу (Р-33).
   * Нет ни того ни другого — вес один, то есть поровну. Остаток от деления —
   * плательщику (Р-32).
   */
  split: { personId: string; share?: number; weight?: number }[]
}

/**
 * Кто кому вернул — это и есть «вернул» (Р-01, Р-30).
 *
 * Принадлежит комнате, а не событию: рассчитываются разом за несколько
 * поводов. Заводится кнопкой в списке «кто кому должен».
 */
export type RoomTransfer = Base & {
  roomId: string
  /** ГГГГ-ММ-ДД */
  date: string
  fromId: string
  toId: string
  /** Целое в валюте комнаты. */
  amount: number
  /** «на Сбер» — банк перевода, если назван. Справочника банков нет: банки чужие. */
  note?: string
}

/** Разовый долг: «дал Пете», «взял у Маши». Без комнаты, события и компании (Р-01). */
export type Loan = Base & {
  personId: string
  direction: 'lent' | 'borrowed'
  money: Money
  /** ГГГГ-ММ-ДД */
  date: string
  note?: string
}

/** Возврат разового долга. Частями — законно (Р-01). */
export type Repayment = Base & {
  loanId: string
  money: Money
  /** ГГГГ-ММ-ДД */
  date: string
}

// ─── Хранилища ─────────────────────────────────────────────────────────────

/**
 * Таблица приложения для ядра: имя синхронизируемого хранилища → тип записи.
 * Она и есть `R` для `AppConfig<R>`.
 */
export type StoreRecord = {
  profile: Profile
  currencies: Currency
  accounts: Account
  categories: Category
  recurring: Recurring
  rates: Rate
  entries: Entry
  balances: Balance
  people: Person
  rooms: Room
  roomEvents: RoomEvent
  roomSpends: RoomSpend
  roomTransfers: RoomTransfer
  loans: Loan
  repayments: Repayment
}

/**
 * Раскладка версии 1 — заморожена после первого релиза (Р-11, Р-12).
 * Восемь хранилищ учёта и снимков; долги пришли миграцией на версию 2
 * и сюда не дописываются никогда.
 */
export const V1_STORES = [
  'profile',
  'currencies',
  'accounts',
  'categories',
  'recurring',
  'rates',
  'entries',
  'balances',
] as const satisfies readonly (keyof StoreRecord)[]

/** Хранилища долгов — версия 2 (Р-30). Их заводит миграция, и только она. */
export const DEBT_STORES = [
  'people',
  'rooms',
  'roomEvents',
  'roomSpends',
  'roomTransfers',
  'loans',
  'repayments',
] as const satisfies readonly (keyof StoreRecord)[]

/** Порядок, в котором хранилища пишут импорт и слепок: справочники раньше записей. */
export const SYNCED_STORES = [...V1_STORES, ...DEBT_STORES] as const satisfies readonly (keyof StoreRecord)[]

export const SCHEMA_VERSION = 2

/**
 * Первая миграция схемы (Р-30).
 *
 * Только добавляет: семь хранилищ долгов. Записи учёта не трогает — значит
 * `additive: true`, и слепок, выгруженный на версии 1, приложение примет.
 *
 * Индексов, кроме `updatedAt`, новые хранилища не получают: он нужен слиянию,
 * а читать по своим ядро всё равно не умеет (отложенная правка ядра).
 * Заводить их впрок второй раз незачем — за год долгов записей сотни.
 */
const DEBTS: Migration = {
  to: 2,
  note: 'Долги Этапа 3: люди, комнаты, события, траты, переводы, разовые долги и возвраты',
  additive: true,
  run: (database) => {
    for (const store of DEBT_STORES) {
      const created = database.createObjectStore(store, { keyPath: 'id' })
      created.createIndex('updatedAt', 'updatedAt') // нужен слиянию
    }
  },
}

export const MIGRATIONS: readonly Migration[] = [DEBTS]

// ─── Даты записей ──────────────────────────────────────────────────────────

/**
 * Дата, по которой запись попадает в месячный файл.
 *
 * У операции — её дата; у итога периода — конец периода (Р-12): к этому
 * месяцу он относится в раскладке, но по месяцам сводок не дробится.
 */
export function entryDate(entry: Entry): string | null {
  return entry.date ?? entry.period?.to ?? null
}
