      <Fold id="help:import" title="Как загружается выписка" folded>
        <ul>
          <li>
            Выписку разбирает беседа с ИИ: вы копируете промпт из приложения, добавляете выписку, а ответ —
            JSON — вставляете обратно. Приложение проверяет каждую запись и показывает сводку{' '}
            <b>до</b> того, как что-то запишет.
          </li>
          <li>
            <b>Выписку берите с последнего загруженного дня включительно</b> — приложение само говорит,
            с какого. Операции этого дня могли появиться уже после того, как прошлая выписка была
            сформирована, а повторы отсекаются сами.
          </li>
          <li>
            Повтор ловится по ключу, который записывается один раз и не меняется. Поэтому переименование
            описания или категории его не ломает.
          </li>
          <li>
            <b>Если беседа разложила операцию не так — правьте её, а не удаляйте.</b> Кнопка «Изменить»
            в списке. Удалённая и внесённая заново операция ключа не имеет, и следующая выписка принесёт
            её второй раз.
          </li>
          <li>
            Если выписок несколько, складывайте их в один файл: перевод между своими счетами виден
            в двух выписках, и записью он должен стать один раз. Сводит их беседа — она видит все
            выписки сразу; приложение само ничего не склеивает, чтобы не принять два разных движения
            за одно.
          </li>
          <li>
            <b>Выписка сверяется по своим же числам.</b> Беседа переносит из неё остатки на начало
            и конец периода, а приложение считает по записям и сравнивает. Не сошлось — операции
            этого счёта не загружаются, и разница называется суммой: значит, перенесено не всё.
            Переводы между своими картами внутри одного банка записями не становятся, но их суммы
            беседа называет отдельно — иначе остаток не сойдётся.
          </li>
          <li>
            Счёт, которого нет в приложении, не заводится наугад: у операции нет валюты — она в валюте
            счёта. Такая запись будет названа, а счёт заводится руками или разделом «accounts».
          </li>
        </ul>
      </Fold>

